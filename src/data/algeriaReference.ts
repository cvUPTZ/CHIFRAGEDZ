export function lookupReferenceBpu(
  designation: string,
  unit: string,
  wilayaCode: string
): { debourseSecDa: number; confidenceRangePct: number } | null {
  const wilaya = ALGERIA_WILAYAS.find((w) => w.code === wilayaCode);
  const regionalFactor = wilaya ? 1 + (wilaya.defaultTransportPct - 2) * 0.008 : 1;

  for (const item of REFERENCE_BPU_CATALOG) {
    if (item.keywords.test(designation)) {
      return {
        debourseSecDa: Math.round(item.baseDebourseSecDa * regionalFactor),
        confidenceRangePct: item.confidenceRangePct,
      };
    }
  }
  return null;
}

