export function buildWhatsappRfqMessage(
  batch: RfqBatch,
  shareUrl: string,
  lang: AppLang
): string {
  const itemLines = batch.items
    .map((it, idx) => `${idx + 1}. [${it.articleNo}] ${it.designation.slice(0, 75)}${it.designation.length > 75 ? '…' : ''} — Qté: ${it.quantity} ${it.unit}`)
    .join('\n');

  if (lang === 'ar') {
    return [
      `السلام عليكم ورحمة الله،`,
      `نرجو منكم موافاتنا بأفضل أسعاركم (دج دون رسوم DA HT) لتوريد المعدات التالية:`,
      `• التخصص: ${batch.trade}`,
      `• ولاية التسليم: ${batch.wilayaName}`,
      `• آخر أجل للرد: ${batch.deadline}`,
      ``,
      itemLines,
      ``,
      `لإدخال أسعاركم أو إرفاق صورة الفاتورة الأولية (Proforma) في أقل من دقيقة بدون تسجيل:`,
      shareUrl,
      ``,
      `شكراً جزيلاً على تعاونكم.`,
    ].join('\n');
  }

  return [
    `Salam Alikoum / Bonjour,`,
    `Merci de nous communiquer vos meilleurs prix unitaires en DA HT (Déboursé / Rendu chantier) pour le lot suivant :`,
    `• Corps d'état : ${batch.trade}`,
    `• Wilaya de livraison : ${batch.wilayaName}`,
    `• Délai souhaité : avant le ${batch.deadline}`,
    ``,
    itemLines,
    ``,
    `Répondez directement en moins de 60 secondes (sans inscription) ou joignez une photo de votre proforma ici :`,
    shareUrl,
    ``,
    `Cordialement.`,
  ].join('\n');
}
